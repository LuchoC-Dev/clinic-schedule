-- Usuarios de la aplicacion. Recepcion administra; el profesional consulta lo propio (D-04).
-- Usuario y profesional son entidades distintas: un usuario con rol PROFESIONAL apunta al
-- profesional que representa. La clave foranea se agrega en la etapa 3, cuando exista la
-- tabla de profesionales.
create table usuario (
    id             bigint generated by default as identity primary key,
    usuario        varchar(50)  not null,
    clave_hash     varchar(100) not null,
    rol            varchar(20)  not null,
    profesional_id bigint,
    activo         boolean      not null default true,
    constraint uq_usuario_usuario unique (usuario),
    constraint ck_usuario_rol check (rol in ('RECEPCION', 'PROFESIONAL')),
    constraint ck_usuario_profesional check (
        (rol = 'PROFESIONAL' and profesional_id is not null)
        or (rol = 'RECEPCION' and profesional_id is null)
    )
);
